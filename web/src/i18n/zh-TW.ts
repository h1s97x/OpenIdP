// WORDS 是「先于单字替换」的词级对照，用于处理多义字与习惯用字差异。
// 例如「制」在「控制」中不作「製」、「台」在「后台」中不作「臺」，
// 若只做单字替换会得到「控製臺」这类错误结果，故这些字不在 MAP 中按单字转换。
